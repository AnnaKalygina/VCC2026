"""Native feature axis -> VCC2026 vocab (18,533 symbols, data/vcc2026/gene_names.csv).

Match order per native feature: (1) exact symbol, (2) Ensembl id via data/vocab_ensembl.tsv,
(3) unique case-insensitive symbol. Several native features hitting one vocab gene are SUMMED;
everything else is dropped before the library size is taken.

    Generated by the ensembl rule in workflow/Snakefile.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import scipy.sparse as sp

ROOT = Path(__file__).resolve().parents[2]
VOCAB_CSV = ROOT / "data/vcc2026/gene_names.csv"
ENS_TSV = ROOT / "data/vocab_ensembl.tsv"


def load_vocab():
    v = pd.read_csv(VOCAB_CSV)["gene_name"].astype(str).to_numpy()
    assert len(v) == 18533 and len(set(v)) == len(v), "VCC2026 vocab must be 18,533 unique symbols"
    return v


class GeneMap:
    """Built once per source axis. `.apply(X_native)` -> counts on the measured-vocab axis."""

    def __init__(self, symbols, ensembl=None, vocab=None, label=""):
        vocab = load_vocab() if vocab is None else vocab
        symbols = np.asarray(symbols).astype(str)
        ens = None if ensembl is None else pd.Series(np.asarray(ensembl).astype(str)).str.split(".").str[0].to_numpy()
        vi = {g: i for i, g in enumerate(vocab)}
        e2v = {}
        if ENS_TSV.exists():
            t = pd.read_csv(ENS_TSV, sep="\t")
            e2v = {e: vi[s] for e, s in zip(t.ensembl, t.symbol)}
        else:
            raise FileNotFoundError(f"{ENS_TSV} missing; run the ensembl workflow rule")
        up = pd.Series(vocab).str.upper()
        dup_up = set(up[up.duplicated(keep=False)])
        ui = {u: i for i, u in enumerate(up) if u not in dup_up}
        # pass 1: exact symbols (duplicates of one exact symbol are true duplicates -> summed)
        tgt = np.full(len(symbols), -1)
        how = np.full(len(symbols), 3)
        for k, s in enumerate(symbols):
            if s in vi:
                tgt[k], how[k] = vi[s], 0
        taken = set(tgt[tgt >= 0])
        # pass 2: rescues may only fill a vocab gene no exact match owns; first rescue wins
        n_shadow = 0
        for k, s in enumerate(symbols):
            if tgt[k] >= 0:
                continue
            v, h = -1, 3
            if ens is not None and ens[k] in e2v:
                v, h = e2v[ens[k]], 1
            elif s.split(".")[0] in e2v:                   # symbol column holding an Ensembl id
                v, h = e2v[s.split(".")[0]], 1
            elif s.upper() in ui:
                v, h = ui[s.upper()], 2
            if v < 0:
                continue
            if v in taken:
                n_shadow += 1                              # same vocab gene already measured -> drop
                continue
            tgt[k], how[k] = v, h
            taken.add(v)
        self.vocab_of = tgt                                   # vocab position per native feature, -1 if dropped
        how = np.bincount(how, minlength=4)
        keep = np.flatnonzero(tgt >= 0)
        self.measured_idx = np.unique(tgt[keep])               # sorted vocab positions
        col = np.searchsorted(self.measured_idx, tgt[keep])
        self.M = sp.csr_matrix((np.ones(len(keep)), (keep, col)), shape=(len(symbols), len(self.measured_idx)))
        n_dup = len(keep) - len(self.measured_idx)
        self.report = dict(n_native=len(symbols), exact=int(how[0]), ensembl=int(how[1]), case=int(how[2]),
                           unmatched=int(how[3]) - n_shadow, rescue_shadowed=n_shadow, summed_duplicates=int(n_dup),
                           n_measured=len(self.measured_idx))
        print(f"[genes{(' ' + label) if label else ''}] {self.report}")
        self.one_to_one = n_dup == 0
        self.src_cols = keep[np.argsort(col)] if self.one_to_one else None

    def apply(self, X):
        """X: [n, n_native] scipy sparse or dense -> csr [n, G_measured] float64."""
        if self.one_to_one:
            return sp.csr_matrix(X)[:, self.src_cols].astype(np.float64)
        return (sp.csr_matrix(X, dtype=np.float64) @ self.M).tocsr()

    def vocab_index(self, symbol_list, vocab=None):
        """Measured-axis index of each symbol (-1 if not measured) -- for the reliability target exclusion."""
        vocab = load_vocab() if vocab is None else vocab
        vi = {g: i for i, g in enumerate(vocab)}
        pos = {v: j for j, v in enumerate(self.measured_idx)}
        return np.array([pos.get(vi.get(s, -1), -1) for s in symbol_list])

